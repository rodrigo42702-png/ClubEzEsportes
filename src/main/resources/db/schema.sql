    CREATE SCHEMA IF NOT EXISTS APP;

    create table APP.clube (
        ativo boolean,
        id bigint generated by default as identity,
        codigo_legado varchar(40) unique,
        cidade varchar(255),
        estado varchar(255),
        nome varchar(255) not null,
        primary key (id)
    );

    create table APP.clube_modalidade (
        ativa boolean,
        capacidade_maxima integer not null,
        clube_id bigint not null,
        id bigint generated by default as identity,
        modalidade_id bigint not null,
        primary key (id),
        constraint uk_clube_modalidade unique (clube_id, modalidade_id)
    );

    create table APP.equipe (
        ativa boolean,
        capacidade_maxima integer not null,
        clube_modalidade_id bigint not null,
        id bigint generated by default as identity,
        codigo_legado varchar(40) unique,
        nome varchar(255) not null,
        primary key (id)
    );

    create table APP.indicador_mensal (
        churn_percentual numeric(12,2),
        competencia date not null,
        receita_mensal numeric(12,2),
        socios_ativos integer,
        clube_id bigint not null,
        id bigint generated by default as identity,
        primary key (id),
        constraint uk_indicador_clube_competencia unique (clube_id, competencia)
    );

    create table APP.inscricao_modalidade (
        data_inscricao date not null,
        clube_modalidade_id bigint not null,
        id bigint generated by default as identity,
        socio_id bigint not null,
        status enum ('ATIVA','CANCELADA','PENDENTE') not null,
        primary key (id)
    );

    create table APP.matricula (
        data_fim date,
        data_inicio date not null,
        valor_contratado numeric(12,2),
        clube_id bigint not null,
        id bigint generated by default as identity,
        plano_id bigint not null,
        socio_id bigint not null,
        codigo_legado varchar(40) unique,
        status enum ('ATIVA','CANCELADA','ENCERRADA','INADIMPLENTE') not null,
        primary key (id)
    );

    create table APP.modalidade (
        ativa boolean,
        id bigint generated by default as identity,
        codigo_legado varchar(40) unique,
        nome varchar(150) not null unique,
        descricao varchar(255),
        primary key (id)
    );

    create table APP.pagamento (
        data_pagamento date,
        valor numeric(12,2),
        vencimento date,
        id bigint generated by default as identity,
        matricula_id bigint not null,
        codigo_legado varchar(40) unique,
        status enum ('ATRASADO','ESTORNADO','PAGO','PENDENTE') not null,
        primary key (id)
    );

    create table APP.participacao_equipe (
        ativa boolean,
        data_entrada date not null,
        data_saida date,
        equipe_id bigint not null,
        id bigint generated by default as identity,
        inscricao_modalidade_id bigint not null,
        primary key (id)
    );

    create table APP.partida_evento (
        data_partida date,
        clube_id bigint not null,
        id bigint generated by default as identity,
        modalidade_id bigint not null,
        codigo_legado varchar(40) unique,
        resultado_mandante varchar(255),
        primary key (id)
    );

    create table APP.perfil (
        id bigint generated by default as identity,
        nome varchar(150) not null unique,
        primary key (id)
    );

    create table APP.plano (
        ativo boolean,
        valor_mensalidade numeric(12,2) not null,
        id bigint generated by default as identity,
        codigo_legado varchar(40) unique,
        nome varchar(255) not null,
        primary key (id)
    );

    create table APP.produto_loja (
        preco_unitario numeric(12,2) not null,
        id bigint generated by default as identity,
        codigo_legado varchar(40) unique,
        categoria varchar(255),
        nome varchar(255) not null,
        primary key (id)
    );

    create table APP.socio (
        ativo boolean,
        data_nascimento date,
        id bigint generated by default as identity,
        codigo_legado varchar(40) unique,
        cpf varchar(150) unique,
        email varchar(150) unique,
        nome varchar(255),
        primary key (id)
    );

    create table APP.treino (
        cancelado boolean,
        data date not null,
        hora_fim time(0),
        hora_inicio time(0),
        equipe_id bigint,
        id bigint generated by default as identity,
        codigo_legado varchar(40) unique,
        clube_legado_codigo varchar(255),
        local varchar(255),
        modalidade_legado_codigo varchar(255),
        primary key (id)
    );

    create table APP.usuario (
        ativo boolean,
        id bigint generated by default as identity,
        perfil_id bigint not null,
        socio_id bigint unique,
        email varchar(150) not null unique,
        senha_hash varchar(255) not null,
        primary key (id)
    );

    create table APP.venda_loja (
        data_venda date not null,
        quantidade integer not null,
        receita numeric(12,2),
        clube_id bigint not null,
        id bigint generated by default as identity,
        produto_loja_id bigint not null,
        codigo_legado varchar(40) unique,
        primary key (id)
    );

